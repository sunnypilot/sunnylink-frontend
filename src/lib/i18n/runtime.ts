const patterns: Array<[RegExp, (...groups: string[]) => string]> = [
	[/^(\d+) devices?$/, (count) => `${count} 個裝置`],
	[/^(\d+) unread$/, (count) => `${count} 則未讀`],
	[/^Copy (.+)$/, (field) => {
		const label = exact[field] ?? field;
		return `複製${/^[A-Za-z]/.test(label) ? ' ' : ''}${label}`;
	}],
	[/^Device details for (.+)$/, (name) => `${name} 的裝置詳細資訊`],
	[/^No settings match "(.+)"$/, (query) => `沒有符合「${query}」的設定`],
	[/^(\d+) marked as read$/, (count) => `已將 ${count} 則標示為已讀`],
	[/^(\d+) marked as unread$/, (count) => `已將 ${count} 則標示為未讀`],
	[/^Failed to encode value for (.+)$/, (key) => `無法編碼 ${key} 的設定值`],
	[/^Device rejected: (.+)$/, (message) => `裝置拒絕變更：${exact[message] ?? message}`],
	[/^(.+) is offline — pick another device$/, (name) => `${name} 目前離線，請選擇其他裝置`],
	[/^Renamed to "(.+)"$/, (name) => `已重新命名為「${name}」`],
	[/^(\d+) changes? failed to sync$/, (count) => `${count} 項變更同步失敗`],
	[/^Cleared (\d+) cached entries\.$/, (count) => `已清除 ${count} 筆快取資料。`]
];

export function translateRuntimeText(input: string): string {
	const normalized = input.replace(/\s+/g, ' ').trim();
	if (!normalized) return input;
	const translated = exact[normalized];
	if (translated) return translated;
	for (const [pattern, replacer] of patterns) {
		const match = normalized.match(pattern);
		if (match) return replacer(...match.slice(1));
	}
	return input;
}
